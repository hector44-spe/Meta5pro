// Color logic extracted from Meta Gold 5
function getSignalColor(strength: number) {
  if (strength === 0) {
    return {
      active: "rgb(255, 51, 68)",
      inactive: "rgba(255, 51, 68, 0.5)",
      textColor: "rgb(255, 51, 68)",
    };
  }
  if (strength < 16) {
    return {
      active: "rgb(255, 51, 68)",
      inactive: "rgba(255, 51, 68, 0.5)",
      textColor: "rgb(255, 51, 68)",
    };
  }
  if (strength < 70) {
    return {
      active: "rgb(249, 226, 106)",
      inactive: "rgba(249, 226, 106, 0.5)",
      textColor: "rgb(249, 226, 106)",
    };
  }
  return {
    active: "rgb(1, 178, 139)",
    inactive: "rgba(1, 178, 139, 0.5)",
    textColor: "rgb(1, 178, 139)",
  };
}

